#!/bin/sh
# Fails if any tracked file looks like a real consumer raw-data export.
# Synthetic fixtures carry a different header on purpose.
set -e
hits=$(git ls-files -z | xargs -0 grep -l -I -E "^# This data file generated by 23andMe|^#AncestryDNA raw data download" 2>/dev/null || true)
if [ -n "$hits" ]; then
  echo "Refusing: these tracked files look like real raw genotype exports:"
  echo "$hits"
  exit 1
fi
echo "ok: no raw genotype exports tracked"
